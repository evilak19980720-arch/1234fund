<?php


namespace App\Http\Resources;


use Illuminate\Http\Resources\Json\JsonResource;

class PaymentDocResource extends JsonResource
{
    public function toArray($request)
    {
        $data = parent::toArray($request); // TODO: Change the autogenerated stub
        if (isset($data['image_url'])) {
            $data['image_url'] = sprintf('%s/%s', aliyun_domain(), $data['image_url']);
        }
        return $data;
    }
}
